// Builds ai/components.json from scripts/data/components.ts, the CSS in src/ and the fixtures in
// test/fixtures/. The summary comes from the first comment of each module, the markup from the
// fixture pages, the token lists from a Lightning CSS pass over the module.
import { existsSync, readFileSync } from "node:fs";
import { EXTRAS, MODULES } from "../compiler/config.ts";
import { entries } from "../../data/components.ts";
import type { Entry, Example, Trigger } from "../../data/components.ts";
import { headerComment, squash, tokenUse } from "./css.ts";
import { script, snippet } from "./html.ts";
import { stringify } from "./json.ts";

type Json = null | boolean | number | string | Json[] | { [key: string]: Json };

const PACKAGE = "@rusticstack/pico-reforged";

function render(example: Example, read: (fixture: string) => string): string {
  if ("html" in example) return example.html;
  return example.finds.map((f) => snippet(read(f.fixture), f)).join("\n");
}

function checkTriggers(entry: Entry, css: string, list: Trigger[] | undefined): string[] {
  const flat = squash(css);
  return (list ?? [])
    .filter((t) => !flat.includes(t.selector))
    .map((t) => `${entry.name}: "${t.selector}" is not in src/${entry.module}.css`);
}

function optIn(entry: Entry): Json {
  const css = `src/${entry.module}.css`;
  if (entry.category === "extras") {
    const name = entry.module.replace(/^extras\//, "");
    return {
      kind: "extra",
      css,
      cdn: `css/extras/${name}.min.css`,
      allExtrasCdn: "css/pico.extras.min.css",
      import: `${PACKAGE}/extras/${name}`,
      config: `@pico { extras: ${name}; }`,
      cli: `pico-reforged build --extras ${name}`,
    };
  }
  if (entry.option) return { kind: "option", css, module: entry.module, how: entry.option.how };
  return { kind: "core", css, module: entry.module, excludeWith: entry.module };
}

export function generateComponents(root: URL): string {
  const files = new Map<string, string>();
  const text = (path: string): string => {
    let value = files.get(path);
    if (value === undefined) {
      value = readFileSync(new URL(path, root), "utf8").replace(/\r\n/g, "\n");
      files.set(path, value);
    }
    return value;
  };
  const fixture = (name: string): string => text(`test/fixtures/${name}`);

  const known = new Set([...MODULES, ...EXTRAS.map((e) => `extras/${e}`)]);
  const out: Json[] = [];
  const problems: string[] = [];
  for (const entry of entries) {
    if (!known.has(entry.module)) throw new Error(`${entry.name}: unknown module ${entry.module}`);
    const path = `src/${entry.module}.css`;
    if (!existsSync(new URL(path, root))) throw new Error(`${entry.name}: ${path} is missing`);
    const css = text(path);
    problems.push(
      ...checkTriggers(entry, css, entry.variants),
      ...checkTriggers(entry, css, entry.states),
    );

    const examples = entry.markup.map((m) => ({ label: m.label, html: render(m, fixture) }));
    const { reads, declares } = tokenUse(css);
    const own = new Set(declares);
    let js: Json = null;
    if (entry.js) {
      js = {
        description: entry.js.description,
        language: "javascript",
        code: "code" in entry.js ? entry.js.code : script(fixture(entry.js.fixture), entry.js.nth),
      };
    }
    const trigger = (t: Trigger): Json => ({
      name: t.name,
      trigger: t.trigger,
      selector: t.selector,
      description: t.description,
    });
    out.push({
      name: entry.name,
      category: entry.category,
      optIn: optIn(entry),
      summary: headerComment(css),
      use: entry.use,
      markup: examples[0]?.html ?? null,
      examples,
      variants: (entry.variants ?? []).map(trigger),
      states: (entry.states ?? []).map(trigger),
      aria: entry.aria,
      ...(entry.notes ? { notes: entry.notes } : {}),
      tokens: { reads: reads.filter((n) => !own.has(n)), defines: declares },
      js,
    });
  }

  if (problems.length > 0) throw new Error(problems.join("\n"));

  return `${stringify({
    description:
      "Components of Pico Reforged, generated by scripts/generate-ai.ts from scripts/data/components.ts, src/ and test/fixtures/. See ai/README.md.",
    package: PACKAGE,
    components: out,
  })}\n`;
}
