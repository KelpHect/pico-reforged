// Writes the generated CSS in src/: tokens/palette.css, tokens/scheme.css, themes/*.css and
// colors/*.css. Run with `node scripts/generate.ts`.
import { mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname } from "node:path";
import { tripleToRgb, formatOklch } from "./lib/color.ts";
import type { Triple } from "./lib/color.ts";
import { palette, schemeValue, STEPS } from "./lib/tokens.ts";
import { builtInTheme } from "./lib/themes.ts";
import { scheme } from "./data/scheme.ts";
import { themes } from "./data/themes.ts";

export { buildTheme } from "./lib/themes.ts";

const GENERATED = "/* Generated by scripts/generate.ts, do not edit by hand. */";
const SELECTOR = ":root,\n:host,\n[data-theme]";

function paletteCss() {
  const lines = [];
  for (const [hue, byStep] of Object.entries(palette.hues)) {
    for (const step of STEPS) lines.push(`  --pico-color-${hue}-${step}: ${formatOklch(byStep[step] as Triple)};`);
    lines.push(`  --pico-color-${hue}: ${formatOklch(byStep[palette.main[hue] as number] as Triple)};`);
  }
  lines.push(`  --pico-color-light: ${formatOklch(palette.white)};`);
  lines.push(`  --pico-color-dark: ${formatOklch(palette.black)};`);
  lines.push(`  --pico-color-black: ${formatOklch(palette.black)};`);
  lines.push(`  --pico-color-white: ${formatOklch(palette.white)};`);
  return `${GENERATED}\n:root,\n:host {\n${lines.join("\n")}\n}\n`;
}

function schemeCss() {
  const decls = scheme.map(([name, light, dark]) => `  --pico-${name}: ${schemeValue(light, dark)};`);
  return `${GENERATED}
:root,
:host {
  color-scheme: light dark;
}

[data-theme="light"] {
  color-scheme: light;
}

[data-theme="dark"] {
  color-scheme: dark;
}

${SELECTOR} {
${decls.join("\n")}
}
`;
}

// Same rule as v2.1.1: light text on dark backgrounds, judged on the sRGB value with the
// W3C brightness formula (299, 587, 114) against half of white.
function textFor(triple: Triple): "light" | "dark" {
  const [r, g, b] = tripleToRgb(triple).map((v) => Math.round(Math.min(255, Math.max(0, v)))) as Triple;
  const brightness = Math.round((r * 299 + g * 587 + b * 114) / 1000);
  return brightness < 127.5 ? "light" : "dark";
}

function utilityCss(kind: "color" | "background"): string {
  const rules = [];
  for (const [hue, byStep] of Object.entries(palette.hues)) {
    const entries: [string, Triple][] = STEPS.map((s) => [`-${s}`, byStep[s] as Triple]);
    entries.push(["", byStep[palette.main[hue] as number] as Triple]);
    for (const [suffix, triple] of entries) {
      const token = `--pico-color-${hue}${suffix}`;
      if (kind === "color") {
        rules.push(`.pico-color-${hue}${suffix} {\n  color: var(${token});\n}`);
      } else {
        rules.push(
          `.pico-background-${hue}${suffix} {\n  background-color: var(${token});\n  color: var(--pico-color-${textFor(triple)});\n}`,
        );
      }
    }
  }
  return `${GENERATED}\n${rules.join("\n\n")}\n`;
}

export function generate(): Record<string, string> {
  const files: Record<string, string> = {
    "src/tokens/palette.css": paletteCss(),
    "src/tokens/scheme.css": schemeCss(),
    "src/colors/colors.css": utilityCss("color"),
    "src/colors/backgrounds.css": utilityCss("background"),
  };
  for (const name of Object.keys(themes)) {
    files[`src/themes/${name}.css`] = builtInTheme(name, `${GENERATED}\n/* Theme: ${name} */`);
  }
  return files;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const root = new URL("../", import.meta.url);
  for (const [path, content] of Object.entries(generate())) {
    const target = fileURLToPath(new URL(path, root));
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, content);
  }
  console.log("generated", Object.keys(generate()).length, "files");
}
